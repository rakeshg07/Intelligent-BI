"""AI SQL Guardrail (ADR-004).

Enforces strictly read-only execution, statement row limits, and AST validation
for any SQL query synthesized by the AI Assistant.
"""

import sqlglot
from sqlglot import exp

from app.core.errors import ValidationError

DISALLOWED_EXPRESSIONS = (
    exp.Insert,
    exp.Update,
    exp.Delete,
    exp.Drop,
    exp.Create,
    exp.Alter,
    exp.Command,
)


class AISQLGuard:
    """Validates and enforces security boundaries on AI-generated SQL."""

    @classmethod
    def validate_and_constrain(
        cls,
        sql: str,
        dialect: str = "duckdb",
        max_rows: int = 500,
        allowed_tables: set[str] | None = None,
    ) -> str:
        """Validate that SQL is strictly read-only and within bounds."""
        cleaned_sql = sql.strip().rstrip(";")
        if not cleaned_sql:
            raise ValidationError("Generated SQL cannot be empty.")

        try:
            parsed = sqlglot.parse_one(cleaned_sql, read=dialect)
        except Exception as e:
            raise ValidationError(f"Invalid SQL syntax generated by AI: {str(e)}") from e

        # 1. Enforce strictly SELECT queries
        if not isinstance(parsed, (exp.Select, exp.Union)):
            raise ValidationError("AI is only permitted to execute SELECT queries.")

        # 2. Check for any nested DML/DDL operations
        for disallowed in DISALLOWED_EXPRESSIONS:
            if parsed.find(disallowed):
                raise ValidationError(
                    f"Disallowed operation '{disallowed.__name__}' detected in AI query."
                )

        # 3. Check allowed tables if provided
        if allowed_tables:
            referenced_tables = {
                table.name.lower() for table in parsed.find_all(exp.Table) if table.name
            }
            disallowed_tables = referenced_tables - {t.lower() for t in allowed_tables}
            if disallowed_tables:
                raise ValidationError(
                    f"AI attempted to query unauthorized table(s): {', '.join(disallowed_tables)}"
                )

        # 4. Enforce row limit
        limit_node = parsed.args.get("limit")
        if limit_node is None:
            parsed = parsed.limit(max_rows)
        else:
            try:
                curr_limit = int(limit_node.expression.this)
                if curr_limit > max_rows or curr_limit <= 0:
                    parsed = parsed.limit(max_rows)
            except Exception:
                parsed = parsed.limit(max_rows)

        return parsed.sql(dialect=dialect)
